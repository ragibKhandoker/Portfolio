-- Applied automatically on backend start when DATABASE_URL is set (or run `npm run db:setup`).
-- You can also paste it into the Supabase SQL editor. Safe to run more than once.

create table if not exists projects (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  technologies text[] not null default '{}',
  project_url text,
  github_url text,
  created_at timestamptz not null default now()
);

create table if not exists skills (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null
);

create table if not exists contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text,
  message text not null,
  created_at timestamptz not null default now()
);

-- The backend uses the service role key, so lock tables down for public (anon) access
alter table projects enable row level security;
alter table skills enable row level security;
alter table contact_messages enable row level security;

insert into projects (title, description, technologies)
select * from (values
  ('Breast Cancer Detection (ML)', 'A comparative study of machine-learning models with a web-based implementation.', '{Python,TensorFlow,React}'::text[]),
  ('ShareMeal', 'A food donation and distribution platform designed to connect communities.', '{React,Node.js,PostgreSQL}'::text[]),
  ('Data Analysis Dashboard', 'Exploratory data analysis and visualization of real-world datasets.', '{Python,Pandas,Matplotlib}'::text[]),
  ('Personal Portfolio', 'A responsive portfolio with a premium dark interface.', '{Next.js,TypeScript,Express}'::text[])
) as seed(title, description, technologies)
where not exists (select 1 from projects);

insert into skills (name, category)
select * from (values
  ('Python', 'Data Science'), ('TensorFlow', 'Machine Learning'), ('Pandas', 'Data Analysis'),
  ('React', 'Frontend'), ('Node.js', 'Backend'), ('PostgreSQL', 'Database'),
  ('Git & GitHub', 'Tools'), ('Docker', 'Tools'), ('VS Code', 'Tools')
) as seed(name, category)
where not exists (select 1 from skills);

-- Make the Supabase REST API see the new tables immediately
notify pgrst, 'reload schema';
